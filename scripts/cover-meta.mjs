import sharp from 'sharp';
import { readdirSync } from 'node:fs';
import { writeFileSync } from 'node:fs';
// Covers live at the root of public/, case-study screens under public/gallery/.
const files = [
  ...readdirSync('public').filter(f => f.endsWith('.webp')),
  ...readdirSync('public/gallery').filter(f => f.endsWith('.webp')).map(f => 'gallery/' + f),
  ...readdirSync('public/covers').filter(f => f.endsWith('.webp')).map(f => 'covers/' + f),
].sort();
const out = {};
for (const f of files) {
  const img = sharp('public/' + f);
  const { width, height } = await img.metadata();
  const buf = await img.resize(16, null, { fit: 'inside' }).webp({ quality: 40 }).toBuffer();
  out['/' + f] = { w: width, h: height, blur: 'data:image/webp;base64,' + buf.toString('base64') };
}
const line = ([k, v]) => `  '${k}': { w: ${v.w}, h: ${v.h}, blur: '${v.blur}' },`;
const entries = Object.entries(out);
const isGallery = ([k]) => k.startsWith('/gallery/');
const coverBody = entries.filter((e) => !isGallery(e)).map(line).join('\n');
const galleryBody = entries.filter(isGallery).map(line).join('\n');
// Two modules: the gallery screens are only drawn on the case-study pages, so
// every other page loads the covers alone (see the note in each file).
writeFileSync('src/lib/cover-meta.js', `/**
 * Intrinsic size and a 16px blur placeholder for every cover (and the other
 * pictures at the root of public/). Generated by scripts/cover-meta.mjs —
 * rerun after adding or replacing a cover.
 *
 * The case-study gallery screens are in gallery-meta.js: only the case-study
 * pages draw them, and they are three quarters of the data, so every other
 * page would otherwise download their placeholders for nothing.
 */
export const COVER_META = {
${coverBody}
};

export const coverMeta = (src) => COVER_META[src] ?? { w: 1920, h: 1000, blur: undefined };
`);
writeFileSync('src/lib/gallery-meta.js', `/**
 * Intrinsic size and a 16px blur placeholder for every case-study gallery
 * screen in public/gallery/. Generated by scripts/cover-meta.mjs — rerun
 * after adding or replacing a screen. Kept apart from cover-meta.js so only
 * the pages that show a gallery load it; DeviceFrame takes it as \`meta\`.
 */
export const GALLERY_META = {
${galleryBody}
};

export const galleryMeta = (src) => GALLERY_META[src] ?? { w: 1920, h: 1000, blur: undefined };
`);
console.log('pictures:', files.length, '| bytes:', coverBody.length + galleryBody.length);
